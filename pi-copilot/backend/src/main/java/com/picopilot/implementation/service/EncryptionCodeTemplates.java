package com.picopilot.implementation.service;

import java.util.List;
import java.util.regex.Pattern;

/**
 * Source files added to a target repository that has no field encryption yet. The cipher uses
 * the same "enc:v1:" AES-256-GCM format as PI Co-Pilot's LOCAL_DEV provider (LocalFieldCipher),
 * so values written by Data Sync and by the application are interchangeable.
 */
public final class EncryptionCodeTemplates {

    static final String KEY_PROPERTY = "pi.encryption.local-key";
    private static final Pattern TOP_LEVEL_PI = Pattern.compile("(?m)^pi:\\s*$");

    private EncryptionCodeTemplates() {}

    static final String CIPHER_CLASS = "PiFieldCipher";
    static final String CONVERTER_CLASS = "PiEncryptedStringConverter";
    static final String DECRYPTOR_CLASS = "PiNativeQueryDecryptor";

    /** The key is read on first use, so a missing key fails the first save or read, not the application start. */
    static String cipher(String pkg) {
        return """
            package %s;

            import org.springframework.core.env.Environment;
            import org.springframework.stereotype.Component;

            import javax.crypto.Cipher;
            import javax.crypto.SecretKey;
            import javax.crypto.spec.GCMParameterSpec;
            import javax.crypto.spec.SecretKeySpec;
            import java.nio.ByteBuffer;
            import java.nio.charset.StandardCharsets;
            import java.security.SecureRandom;
            import java.util.Base64;

            /**
             * AES-256-GCM field encryption, generated by PI Co-Pilot. Matches its LOCAL_DEV provider:
             * both sides must share the same %s. Values without the "enc:v1:" prefix are
             * treated as plain text. The key is loaded on first use.
             */
            @Component
            public class PiFieldCipher {

                public static final String PREFIX = "enc:v1:";
                private static final String KEY_PROPERTY = "%s";
                private static final String TRANSFORMATION = "AES/GCM/NoPadding";
                private static final int IV_BYTES = 12;
                private static final int TAG_BITS = 128;

                private final Environment environment;
                private final SecureRandom random = new SecureRandom();
                private volatile SecretKey key;

                public PiFieldCipher(Environment environment) {
                    this.environment = environment;
                }

                private SecretKey key() {
                    SecretKey k = key;
                    if (k == null) {
                        String base64Key = environment.getProperty(KEY_PROPERTY, "");
                        byte[] keyBytes = Base64.getDecoder().decode(base64Key);
                        if (keyBytes.length != 32) {
                            throw new IllegalStateException(KEY_PROPERTY + " must be a base64-encoded 32-byte key");
                        }
                        k = key = new SecretKeySpec(keyBytes, "AES");
                    }
                    return k;
                }

                public boolean isEncrypted(String value) {
                    return value != null && value.startsWith(PREFIX);
                }

                public String encrypt(String plaintext) {
                    if (plaintext == null || isEncrypted(plaintext)) return plaintext;
                    try {
                        byte[] iv = new byte[IV_BYTES];
                        random.nextBytes(iv);
                        Cipher cipher = Cipher.getInstance(TRANSFORMATION);
                        cipher.init(Cipher.ENCRYPT_MODE, key(), new GCMParameterSpec(TAG_BITS, iv));
                        byte[] ct = cipher.doFinal(plaintext.getBytes(StandardCharsets.UTF_8));
                        return PREFIX + Base64.getEncoder().encodeToString(
                            ByteBuffer.allocate(iv.length + ct.length).put(iv).put(ct).array());
                    } catch (IllegalStateException e) {
                        throw e;
                    } catch (Exception e) {
                        throw new IllegalStateException("Failed to encrypt field value", e);
                    }
                }

                public String decrypt(String value) {
                    if (!isEncrypted(value)) return value;
                    try {
                        byte[] data = Base64.getDecoder().decode(value.substring(PREFIX.length()));
                        Cipher cipher = Cipher.getInstance(TRANSFORMATION);
                        cipher.init(Cipher.DECRYPT_MODE, key(), new GCMParameterSpec(TAG_BITS, data, 0, IV_BYTES));
                        return new String(cipher.doFinal(data, IV_BYTES, data.length - IV_BYTES), StandardCharsets.UTF_8);
                    } catch (IllegalStateException e) {
                        throw e;
                    } catch (Exception e) {
                        throw new IllegalStateException("Failed to decrypt field value", e);
                    }
                }
            }
            """.formatted(pkg, KEY_PROPERTY, KEY_PROPERTY);
    }

    /**
     * Implementation: each entity's {@code <field>Encrypted} copy maps to its "_enc" column through this converter;
     * after a successful release the plain fields move onto the "_enc" columns through it too. Spring Boot lets
     * Hibernate create converters as Spring beans, so the cipher is injected.
     */
    static String converter(String pkg, String persistence) {
        return """
            package %s;

            import %s.AttributeConverter;
            import %s.Converter;
            import org.springframework.stereotype.Component;

            /**
             * Generated by PI Co-Pilot. Entity fields stored in an "_enc" column are mapped through this converter:
             * values are encrypted on write and decrypted on read.
             */
            @Component
            @Converter
            public class PiEncryptedStringConverter implements AttributeConverter<String, String> {

                private final PiFieldCipher cipher;

                public PiEncryptedStringConverter(PiFieldCipher cipher) {
                    this.cipher = cipher;
                }

                @Override
                public String convertToDatabaseColumn(String value) {
                    return cipher.encrypt(value);
                }

                @Override
                public String convertToEntityAttribute(String value) {
                    return cipher.decrypt(value);
                }
            }
            """.formatted(pkg, persistence, persistence);
    }

    /**
     * Native queries read the "_enc" columns themselves, so their rows carry ciphertext; this decrypts the
     * "enc:v1:" values in every native query result.
     */
    static String nativeQueryDecryptor(String pkg) {
        return """
            package %s;

            import org.aopalliance.intercept.MethodInterceptor;
            import org.springframework.aop.framework.ProxyFactory;
            import org.springframework.beans.factory.ObjectProvider;
            import org.springframework.beans.factory.config.BeanPostProcessor;
            import org.springframework.core.annotation.AnnotationUtils;
            import org.springframework.data.jpa.repository.Query;
            import org.springframework.data.repository.Repository;
            import org.springframework.stereotype.Component;
            import org.springframework.util.ClassUtils;

            import java.lang.reflect.Method;
            import java.util.Arrays;
            import java.util.Collection;
            import java.util.Map;
            import java.util.Optional;
            import java.util.concurrent.ConcurrentHashMap;

            /**
             * Generated by PI Co-Pilot. Native queries return raw rows read from the encrypted columns;
             * this decrypts the "enc:v1:" values in their results, so callers get the same plain values as before.
             */
            @Component
            public class PiNativeQueryDecryptor implements BeanPostProcessor {

                private final ObjectProvider<PiFieldCipher> cipher;
                private final Map<Method, Boolean> nativeMethods = new ConcurrentHashMap<>();

                public PiNativeQueryDecryptor(ObjectProvider<PiFieldCipher> cipher) {
                    this.cipher = cipher;
                }

                @Override
                public Object postProcessAfterInitialization(Object bean, String beanName) {
                    if (!(bean instanceof Repository) || Arrays.stream(ClassUtils.getAllInterfaces(bean))
                        .flatMap(i -> Arrays.stream(i.getMethods())).noneMatch(this::isNative)) {
                        return bean;
                    }
                    ProxyFactory factory = new ProxyFactory(bean);
                    factory.addAdvice((MethodInterceptor) invocation -> {
                        Object result = invocation.proceed();
                        return isNative(invocation.getMethod()) ? decryptResult(result) : result;
                    });
                    return factory.getProxy();
                }

                private boolean isNative(Method method) {
                    return nativeMethods.computeIfAbsent(method, m -> {
                        Query query = AnnotationUtils.findAnnotation(m, Query.class);
                        return query != null && query.nativeQuery();
                    });
                }

                private Object decryptResult(Object result) {
                    if (result instanceof Object[]) {
                        decryptRow((Object[]) result);
                    } else if (result instanceof Collection) {
                        for (Object item : (Collection<?>) result) {
                            if (item instanceof Object[]) decryptRow((Object[]) item);
                        }
                    } else if (result instanceof Optional) {
                        ((Optional<?>) result).ifPresent(item -> {
                            if (item instanceof Object[]) decryptRow((Object[]) item);
                        });
                    } else if (result instanceof String && cipher.getObject().isEncrypted((String) result)) {
                        return cipher.getObject().decrypt((String) result);
                    }
                    return result;
                }

                private void decryptRow(Object[] row) {
                    PiFieldCipher c = cipher.getObject();
                    for (int i = 0; i < row.length; i++) {
                        if (row[i] instanceof String && c.isEncrypted((String) row[i])) {
                            row[i] = c.decrypt((String) row[i]);
                        } else if (row[i] instanceof Object[]) {
                            decryptRow((Object[]) row[i]); // single-row results can arrive wrapped
                        }
                    }
                }
            }
            """.formatted(pkg);
    }

    /** Flyway migration dropping the plain columns after a successful release (idempotent). */
    static String dropMigration(List<String> ddl) {
        return "-- Generated by PI Co-Pilot after a successful release: the plain-text PI columns are retired.\n"
            + "-- Every value lives encrypted in its \"_enc\" column; IF EXISTS keeps this idempotent.\n"
            + String.join("\n", ddl) + "\n";
    }

    /** Flyway migration matching the columns already added to the database (idempotent). */
    static String migration(List<String> ddl) {
        return "-- Generated by PI Co-Pilot: encrypted copies of PI columns.\n"
            + "-- PI Co-Pilot already applied these to the database; IF NOT EXISTS keeps them idempotent.\n"
            + String.join("\n", ddl) + "\n";
    }

    /**
     * application.yml with the key property appended, or null if it already has one or has a
     * top-level "pi:" block we must not duplicate (YAML forbids duplicate keys).
     *
     * @param localDevKey LOCAL_DEV key used as the default, so the application runs with the same key as
     *                    PI Co-Pilot out of the box (development only; other environments set the variable)
     */
    static String withYamlKey(String yaml, String localDevKey) {
        if (yaml.contains("local-key") || TOP_LEVEL_PI.matcher(yaml).find()) return null;
        return yaml.replaceAll("\\s+$", "") + "\n\npi:\n  encryption:\n"
            + "    # Base64 AES-256 key shared with PI Co-Pilot's LOCAL_DEV provider (development only)\n"
            + "    local-key: " + keyReference(localDevKey) + "\n";
    }

    static String withPropertiesKey(String properties, String localDevKey) {
        if (properties.contains(KEY_PROPERTY)) return null;
        return properties.replaceAll("\\s+$", "") + "\n\n# Base64 AES-256 key shared with PI Co-Pilot's LOCAL_DEV provider (development only)\n"
            + KEY_PROPERTY + "=" + keyReference(localDevKey) + "\n";
    }

    private static String keyReference(String localDevKey) {
        return localDevKey == null || localDevKey.isBlank()
            ? "${PI_LOCAL_ENCRYPTION_KEY}" : "${PI_LOCAL_ENCRYPTION_KEY:" + localDevKey + "}";
    }
}
