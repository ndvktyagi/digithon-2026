package com.digithon.hr.security;

import org.aopalliance.intercept.MethodInterceptor;
import org.springframework.aop.framework.ProxyFactory;
import org.springframework.beans.factory.ObjectProvider;
import org.springframework.beans.factory.config.BeanPostProcessor;
import org.springframework.data.repository.Repository;
import org.springframework.stereotype.Component;

import java.lang.reflect.InvocationTargetException;
import java.lang.reflect.Method;
import java.util.Arrays;
import java.util.Collection;
import java.util.Map;
import java.util.Optional;
import java.util.concurrent.ConcurrentHashMap;

/**
 * Generated by PI Co-Pilot. Native queries return raw rows, so PiEncryptionListener never sees them.
 * PI Co-Pilot added a twin "{name}PiEncrypted" next to each native query that reads PI; the original
 * methods are unchanged. While encrypted read is on, a call to the original runs its twin instead and the
 * "enc:v1:" values in the returned rows are decrypted, so the caller gets the same row shape.
 * While it is off, every call goes straight to the original method.
 */
@Component
public class PiNativeQueryRouter implements BeanPostProcessor {

    static final String SUFFIX = "PiEncrypted";

    private final ObjectProvider<PiFieldCipher> cipher;
    private final Map<Method, Optional<Method>> twins = new ConcurrentHashMap<>();

    public PiNativeQueryRouter(ObjectProvider<PiFieldCipher> cipher) {
        this.cipher = cipher;
    }

    @Override
    public Object postProcessAfterInitialization(Object bean, String beanName) {
        if (!(bean instanceof Repository)
            || Arrays.stream(bean.getClass().getMethods()).noneMatch(m -> m.getName().endsWith(SUFFIX))) {
            return bean;
        }
        ProxyFactory factory = new ProxyFactory(bean);
        factory.addAdvice((MethodInterceptor) invocation -> {
            if (!PiEncryptionFlags.encryptedRead()) return invocation.proceed();
            Optional<Method> twin = twins.computeIfAbsent(invocation.getMethod(), m -> twinOf(bean, m));
            if (twin.isEmpty()) return invocation.proceed();
            try {
                return decryptResult(twin.get().invoke(bean, invocation.getArguments()));
            } catch (InvocationTargetException e) {
                throw e.getTargetException();
            }
        });
        return factory.getProxy();
    }

    private static Optional<Method> twinOf(Object bean, Method method) {
        if (method.getName().endsWith(SUFFIX)) return Optional.empty();
        try {
            return Optional.of(bean.getClass().getMethod(method.getName() + SUFFIX, method.getParameterTypes()));
        } catch (NoSuchMethodException e) {
            return Optional.empty();
        }
    }

    private Object decryptResult(Object result) {
        if (result instanceof Object[]) {
            decryptRow((Object[]) result);
        } else if (result instanceof Collection) {
            for (Object item : (Collection<?>) result) {
                if (item instanceof Object[]) decryptRow((Object[]) item);
            }
        } else if (result instanceof Optional) {
            ((Optional<?>) result).ifPresent(item -> {
                if (item instanceof Object[]) decryptRow((Object[]) item);
            });
        }
        return result;
    }

    private void decryptRow(Object[] row) {
        PiFieldCipher c = cipher.getObject();
        for (int i = 0; i < row.length; i++) {
            if (row[i] instanceof String && c.isEncrypted((String) row[i])) {
                row[i] = c.decrypt((String) row[i]);
            } else if (row[i] instanceof Object[]) {
                decryptRow((Object[]) row[i]); // single-row results can arrive wrapped
            }
        }
    }
}
